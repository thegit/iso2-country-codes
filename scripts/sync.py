#!/usr/bin/env python3
"""Pull the latest data from iso2.com, sanity-check it, and write it into
data/ and both packages. Standard library only. Exit 0 = ok (changed or not)."""
import json
import sys
import urllib.request
from pathlib import Path

BASE = "https://iso2.com/data/"
ROOT = Path(__file__).resolve().parent.parent
UA = {"User-Agent": "iso2-country-codes-sync (+https://github.com/thegit/iso2-country-codes)"}


def get(name):
    req = urllib.request.Request(BASE + name, headers=UA)
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def main():
    files = {n: get(n) for n in ("countries.json", "subdivisions.json",
                                 "countries.csv", "subdivisions.csv")}
    countries = json.loads(files["countries.json"])["countries"]
    subdivisions = json.loads(files["subdivisions.json"])["subdivisions"]
    updated = json.loads(files["countries.json"])["updated"]
    if not 240 <= len(countries) <= 256 or len(subdivisions) < 3000:
        sys.exit(f"Refusing suspicious data: {len(countries)} countries, "
                 f"{len(subdivisions)} subdivisions")

    for name, blob in files.items():
        (ROOT / "data" / name).write_bytes(blob)

    slim = {"updated": updated, "countries": countries, "subdivisions": subdivisions}
    payload = json.dumps(slim, ensure_ascii=False, separators=(",", ":"))

    # JavaScript: a plain ES module so it works in Node, Deno, Bun and bundlers.
    (ROOT / "packages/js/data.js").write_text(
        "// Generated by scripts/sync.py from https://iso2.com - do not edit.\n"
        f"export default {payload};\n", encoding="utf-8")
    # Python: JSON bundled inside the package.
    (ROOT / "packages/python/src/iso2/data.json").write_text(payload, encoding="utf-8")
    print(f"Synced {len(countries)} countries, {len(subdivisions)} subdivisions "
          f"(updated {updated})")


if __name__ == "__main__":
    main()
